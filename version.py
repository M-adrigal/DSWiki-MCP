def version_summary() -> dict:
    """当前版本与四层口径的自述，供 service_control(status) 直接带出。

    让服务自己讲清「现在跑的是哪一版、哪层口径动过、要不要重算」，
    而不是靠服务之外的文档——文档总会落后于代码。
    """
    last = CHANGELOG[-1]
    return {
        "口径版本": ENGINE_VERSION,
        "规则指纹": rules_fingerprint(),
        "工具层指纹": server_fingerprint(),
        "本版需重算": last["需重算"],
        "本版变更": last["变更"],
        "本版说明": last["说明"],
        "变更记录条数": len(CHANGELOG),
        "口径分层": CALIBERS,
        "重算判据": "看 CHANGELOG 的「需重算」，不是看版本号或指纹。"
                   "指纹变了先按三步确认：比输入指纹 → 比同一文档 score → 分数没变就不用重算",
    }


def needs_rebuild(spec_version: str | None) -> tuple:
    """返回 (是否需要重算, 原因)"""
    if not spec_version:
        return True, "spec.json 未记录口径版本，无法判断是否受影响，按需重算处理"
    if spec_version == ENGINE_VERSION:
        return False, "口径版本一致"
    if spec_version > ENGINE_VERSION:
        # 画像由更新版引擎生成，当前引擎无法验证它的数字，不能说"没问题"
        return True, (f"画像口径版本 {spec_version} 比当前引擎 {ENGINE_VERSION} 更新，"
                      "当前引擎无法验证其数字，需用新版引擎复核或回退版本")
    changed = [c for c in CHANGELOG
               if c["需重算"] and c["version"] > spec_version]
    if not changed:
        return False, f"版本落后（{spec_version} → {ENGINE_VERSION}）但无影响指标"
    affects = sorted({m for c in changed for m in c["影响指标"]})
    return True, f"口径已变更（{spec_version} → {ENGINE_VERSION}），受影响指标：{'、'.join(affects)}"


# 规则指纹只覆盖「决定数字怎么算」的引擎模块。**不含 server.py**。
# 这是刻意的：改接口、加 preset、改 stats 都不该让指纹变，
# 否则指纹就失去「数字算法是否变过」这个语义。
RULE_MODULES = ("docx_probe", "style_probe", "quality_gate",
                "pptx_quality_gate", "cluster_gate", "batch_compare")

# 工具层指纹覆盖入口与配置。它管的是「接口行为有没有变」：
# 加参数、改返回结构、改错误文案都算变。
TOOL_MODULES = ("mcp_server/server.py", "service_config.py")


def _file_sha(rel: str) -> str:
    """相对路径取源码摘要。server.py 在 mcp_server/ 下，按相对项目根解析。"""
    import hashlib
    from pathlib import Path
    base = Path(__file__).resolve().parent
    f = base / rel
    if not f.exists():
        return "missing"
    return hashlib.sha1(f.read_bytes()).hexdigest()[:8]


def server_fingerprint() -> str:
    """入口层指纹：server.py + service_config.py。

    **为什么需要它**：规则指纹只覆盖 6 个引擎模块，改 server.py（加 preset、
    改 stats、改返回结构）不会让规则指纹变。结果是「返工了但指纹没变」，
    没法从结果里判断跑的是改前还是改后的服务。
    两个指纹分工：规则指纹答「数字怎么算」，工具层指纹答「接口长什么样」。
    """
    import hashlib
    parts = [f"{rel}:{_file_sha(rel)}" for rel in TOOL_MODULES]
    return hashlib.sha1("|".join(parts).encode()).hexdigest()[:12]


def rules_fingerprint() -> str:
    """统计规则指纹：只覆盖 6 个引擎模块的源码摘要。

    答的是「数字怎么算」。两次调用指纹不同 = 统计规则被改过，分数变化有据可查。
    **改 server.py 不会让它变**——那属于工具层，看 server_fingerprint()。

    ⚠️ 它是**保守**的：引擎模块里**任何**改动都会让指纹变，
    哪怕只改了一句展示措辞、没有动任何算法（例如把交付检查的「缺失」
    改成「存在残留」，分数一分没变，指纹照样变）。

    这是有意的取舍：宁可多提示一次重算，也不能放过一次真实的口径变更。
    所以看到「指纹变了」不要直接下结论，按三步确认：
      1. 先比 _审计.输入指纹 —— 不同说明是文件变了，跟代码无关
      2. 再比同一份文档的 score —— 分数没变说明只动了展示层，不必重算
      3. 分数变了才需要全量重算已有画像

    这正是「13 分钟内 93→100 说不清原因」的解法：不是保证结果不变，
    而是保证变化可归因。
    """
    import hashlib
    parts = []
    for name in RULE_MODULES:
        mod = __import__(name)
        src = getattr(mod, "__file__", None)
        if not src:
            continue
        with open(src, "rb") as f:
            parts.append(f"{name}:{hashlib.sha1(f.read()).hexdigest()[:8]}")
    return hashlib.sha1("|".join(parts).encode()).hexdigest()[:12]
